import { GoogleGenAI } from "@google/genai";

const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

/**
 * Converts a File object to a Base64 string suitable for the Gemini API.
 */
const fileToBase64 = (file: File): Promise<string> => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.readAsDataURL(file);
    reader.onload = () => {
      const result = reader.result as string;
      // Remove the Data URL prefix (e.g., "data:application/pdf;base64,")
      const base64Data = result.split(',')[1];
      resolve(base64Data);
    };
    reader.onerror = (error) => reject(error);
  });
};

/**
 * Sends the PDF to Gemini and requests an HTML conversion.
 */
export const convertPdfToHtml = async (file: File): Promise<string> => {
  try {
    const base64Data = await fileToBase64(file);

    const prompt = `
      You are an expert document conversion engine. 
      Task: Convert the content of the attached PDF file into clean, semantic HTML format.
      
      CRITICAL REQUIREMENT FOR PAGINATION:
      - You MUST detect where one page ends and the next begins in the source PDF.
      - **Between every physical page**, insert exactly this HTML element: <div class="page-break"></div>
      - Do NOT merge all pages into one continuous text. Keep the logical separation.

      Formatting Requirements:
      1. Output ONLY the raw HTML body content (do not include <html>, <head>, or <body> tags).
      2. Use <h1>, <h2>, <h3> for headings.
      3. Use <p> for paragraphs.
      4. Use <table>, <tr>, <td>, <th> for tables. Ensure borders are defined in style attributes (e.g., style="border: 1px solid black; border-collapse: collapse;").
      5. Preserve bold (<b> or <strong>) and italic (<i> or <em>) formatting.
      6. If there are lists, use <ul>/<li> or <ol>/<li>.
      7. Keep the content in the original language (Arabic/English/etc.).
      
      Start directly with the content.
    `;

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: {
        parts: [
          {
            inlineData: {
              mimeType: file.type,
              data: base64Data
            }
          },
          {
            text: prompt
          }
        ]
      }
    });

    const text = response.text;
    if (!text) {
      throw new Error("No content generated by Gemini.");
    }

    // Clean up if the model accidentally included markdown blocks despite instructions
    let cleanText = text.trim();
    if (cleanText.startsWith('```html')) {
      cleanText = cleanText.replace(/^```html/, '').replace(/```$/, '');
    } else if (cleanText.startsWith('```')) {
      cleanText = cleanText.replace(/^```/, '').replace(/```$/, '');
    }

    return cleanText;
  } catch (error) {
    console.error("Gemini Conversion Error:", error);
    throw error;
  }
};